import math

# Generates:
#  - KNOT_CENTERLINE_D: a plain rounded-rect path used as the motion path for
#    characters/shapes to walk along (independent of the decorative border).
#  - KNOT_CHAIN_PATHS: a chain of interlocking figure-8 (lemniscate) loops
#    strung along that same centerline, which is what actually reads as a
#    woven Celtic-style knotwork border.

W, H = 800, 300
PAD = 34
R = 26  # corner radius of the rounded-rect centerline

x0, y0 = PAD, PAD
x1, y1 = W - PAD, H - PAD
w = x1 - x0
h = y1 - y0

straight_top = w - 2*R
straight_right = h - 2*R
straight_bottom = straight_top
straight_left = straight_right
arc = (math.pi/2) * R
perimeter = 2*straight_top + 2*straight_right + 4*arc

def point_at(s):
    """s in [0, perimeter): returns (x,y, tangent_angle) walking clockwise from top-mid."""
    segs = [
        ("top_right_half", straight_top/2),
        ("corner_tr", arc),
        ("right", straight_right),
        ("corner_br", arc),
        ("bottom", straight_bottom),
        ("corner_bl", arc),
        ("left", straight_left),
        ("corner_tl", arc),
        ("top_left_half", straight_top/2),
    ]
    rem = s % perimeter
    for name, length in segs:
        if rem <= length:
            t = rem / length if length > 0 else 0
            if name == "top_right_half":
                x = x0 + w/2 + t * (straight_top/2); y = y0; ang = 0
            elif name == "corner_tr":
                a = -math.pi/2 + t*(math.pi/2)
                x = x1 - R + R*math.cos(a); y = y0 + R + R*math.sin(a); ang = a + math.pi/2
            elif name == "right":
                x = x1; y = y0 + R + t*straight_right; ang = math.pi/2
            elif name == "corner_br":
                a = 0 + t*(math.pi/2)
                x = x1 - R + R*math.cos(a); y = y1 - R + R*math.sin(a); ang = a + math.pi/2
            elif name == "bottom":
                x = x1 - R - t*straight_bottom; y = y1; ang = math.pi
            elif name == "corner_bl":
                a = math.pi/2 + t*(math.pi/2)
                x = x0 + R + R*math.cos(a); y = y1 - R + R*math.sin(a); ang = a + math.pi/2
            elif name == "left":
                x = x0; y = y1 - R - t*straight_left; ang = -math.pi/2
            elif name == "corner_tl":
                a = math.pi + t*(math.pi/2)
                x = x0 + R + R*math.cos(a); y = y0 + R + R*math.sin(a); ang = a + math.pi/2
            elif name == "top_left_half":
                x = x0 + t*(straight_top/2); y = y0; ang = 0
            return x, y, ang
        rem -= length
    return x0 + w/2, y0, 0

def fmt(v):
    return f"{v:.2f}"

def path_d(points, close=False):
    d = f"M {fmt(points[0][0])} {fmt(points[0][1])} "
    d += " ".join(f"L {fmt(px)} {fmt(py)}" for px, py in points[1:])
    if close:
        d += " Z"
    return d

# --- Motion centerline (plain rounded rect) ---
N_SAMPLES = 1200
centerline_pts = []
for i in range(N_SAMPLES + 1):
    s = (i / N_SAMPLES) * perimeter
    x, y, _ = point_at(s)
    centerline_pts.append((x, y))
centerline_d = path_d(centerline_pts, close=True)

# --- Decorative chain-of-loops border ---
N_UNITS = 26
AMP = 15.0        # half-height of each loop, perpendicular to the path
LEN_SCALE = 1.35  # how much of the unit spacing each loop's long axis spans
STEPS = 60

def lemniscate(theta, a):
    denom = 1 + math.sin(theta) ** 2
    x = a * math.cos(theta) / denom
    y = a * math.sin(theta) * math.cos(theta) / denom
    return x, y

spacing = perimeter / N_UNITS
chain_paths = []
for i in range(N_UNITS):
    s_center = i * spacing
    x, y, ang = point_at(s_center)
    tx, ty = math.cos(ang), math.sin(ang)
    nx, ny = -ty, tx
    a = spacing * LEN_SCALE / 2
    pts = []
    for st in range(STEPS + 1):
        theta = (st / STEPS) * 2 * math.pi
        lx, ly = lemniscate(theta, a)
        py_scaled = ly * (AMP / (a * 0.5))
        px = x + tx * lx + nx * py_scaled
        pyv = y + ty * lx + ny * py_scaled
        pts.append((px, pyv))
    chain_paths.append(path_d(pts))

with open("/home/ndot/Work/twitch-alerts/theme/knot-path-data.js", "w") as f:
    f.write("// AUTO-GENERATED by scripts/gen_knot.py -- do not hand-edit, regenerate instead\n")
    f.write("export const KNOT_CENTERLINE_D = " + repr(centerline_d) + ";\n")
    f.write("export const KNOT_PERIMETER_BOX = { x: %s, y: %s, w: %s, h: %s };\n" % (fmt(x0), fmt(y0), fmt(w), fmt(h)))
    f.write("export const KNOT_CHAIN_PATHS = [\n")
    for d in chain_paths:
        f.write("  " + repr(d) + ",\n")
    f.write("];\n")

print("perimeter:", perimeter, "loops:", len(chain_paths))
